-- 1. PARA BİRİMLERİ (CURRENCIES)
CREATE TABLE IF NOT EXISTS currencies (
    code VARCHAR(10) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(10) NOT NULL,
    is_base INTEGER DEFAULT 0
);

-- 2. DÖVİZ KURLARI (EXCHANGE_RATES)
CREATE TABLE IF NOT EXISTS exchange_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_date DATE NOT NULL,
    currency_code VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    buying_rate NUMERIC(15,4) NOT NULL,
    selling_rate NUMERIC(15,4) NOT NULL,
    source VARCHAR(50) DEFAULT 'MANUAL',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(rate_date, currency_code)
);

-- 3. CARİ HESAPLAR / KİŞİLER (ACCOUNTS)
CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    account_type VARCHAR(50) NOT NULL,
    tax_office VARCHAR(100),
    tax_number VARCHAR(50),
    phone VARCHAR(50),
    email VARCHAR(100),
    address TEXT,
    authorized_person VARCHAR(100),
    description TEXT,
    default_currency VARCHAR(10) DEFAULT 'TRY' REFERENCES currencies(code) ON DELETE RESTRICT,
    active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. KASA VE BANKA HESAPLARI (CASH_BANKS)
CREATE TABLE IF NOT EXISTS cash_banks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL,
    currency_code VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    account_number VARCHAR(100),
    bank_name VARCHAR(100),
    branch_name VARCHAR(100),
    description TEXT,
    active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. İŞLEMLER (TRANSACTIONS)
CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx_number VARCHAR(100) UNIQUE NOT NULL,
    tx_date DATE NOT NULL,
    tx_type VARCHAR(50) NOT NULL,
    reference_no VARCHAR(100),
    description TEXT,
    status VARCHAR(20) DEFAULT 'CONFIRMED',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT
);

-- 6. İŞLEM KALEMLERİ (TRANSACTION_LINES)
CREATE TABLE IF NOT EXISTS transaction_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
    line_no INTEGER NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    cash_bank_id BIGINT REFERENCES cash_banks(id) ON DELETE SET NULL,
    direction VARCHAR(10) NOT NULL,
    currency_code VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    amount NUMERIC(18,4) NOT NULL,
    exchange_rate NUMERIC(15,4) NOT NULL,
    base_amount NUMERIC(18,4) NOT NULL,
    description TEXT,
    due_date DATE
);

-- 7. DÖVİZ FIFO LOTLARI (FX_LOTS)
CREATE TABLE IF NOT EXISTS fx_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_number VARCHAR(100),
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    cash_bank_id BIGINT REFERENCES cash_banks(id) ON DELETE SET NULL,
    transaction_line_id BIGINT NOT NULL REFERENCES transaction_lines(id) ON DELETE CASCADE,
    entry_date DATE NOT NULL,
    currency_code VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    initial_amount NUMERIC(18,4) NOT NULL,
    remaining_amount NUMERIC(18,4) NOT NULL,
    exchange_rate NUMERIC(15,4) NOT NULL,
    base_amount NUMERIC(18,4) NOT NULL,
    status VARCHAR(20) DEFAULT 'OPEN',
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. LOT TAHSİSATLARI (FX_LOT_ALLOCATIONS)
CREATE TABLE IF NOT EXISTS fx_lot_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id BIGINT NOT NULL REFERENCES fx_lots(id) ON DELETE CASCADE,
    transaction_line_id BIGINT NOT NULL REFERENCES transaction_lines(id) ON DELETE CASCADE,
    allocated_amount NUMERIC(18,4) NOT NULL,
    exit_rate NUMERIC(15,4),
    entry_rate NUMERIC(15,4),
    profit_loss NUMERIC(18,4),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 9. DENETİM İZİ (AUDIT_LOGS)
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(100) NOT NULL,
    entity_name VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 10. DÖVİZ BAĞLANTI İŞLEMLERİ (FX_CONTRACTS)
CREATE TABLE IF NOT EXISTS fx_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_number VARCHAR(100) UNIQUE NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE RESTRICT,
    sell_currency VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    sell_amount NUMERIC(18,4) NOT NULL,
    buy_currency VARCHAR(10) NOT NULL REFERENCES currencies(code) ON DELETE RESTRICT,
    unit_price NUMERIC(15,6) NOT NULL,
    total_target_amount NUMERIC(18,4) NOT NULL,
    collected_amount NUMERIC(18,4) DEFAULT 0,
    remaining_amount NUMERIC(18,4) NOT NULL,
    contract_date DATE NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 11. DÖVİZ BAĞLANTI ÖDEMELERİ (FX_CONTRACT_PAYMENTS)
CREATE TABLE IF NOT EXISTS fx_contract_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id BIGINT NOT NULL REFERENCES fx_contracts(id) ON DELETE CASCADE,
    transaction_id BIGINT REFERENCES transactions(id) ON DELETE SET NULL,
    amount NUMERIC(18,4) NOT NULL,
    currency_code VARCHAR(10) REFERENCES currencies(code) ON DELETE RESTRICT,
    payment_date DATE NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 12. KULLANICI YÖNETİMİ & GÜVENLİK (APP_USERS)
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    salt VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    role VARCHAR(50) DEFAULT 'ADMIN',
    active INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 13. OTURUM YÖNETİMİ (APP_SESSIONS)
CREATE TABLE IF NOT EXISTS app_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    token VARCHAR(255) UNIQUE NOT NULL,
    token_hash VARCHAR(255),
    expires_at TIMESTAMPTZ NOT NULL,
    ip_address VARCHAR(100),
    user_agent TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- İNDEKSLER (Performans ve Hızlı Arama)
CREATE INDEX IF NOT EXISTS idx_tx_lines_account ON transaction_lines(account_id);
CREATE INDEX IF NOT EXISTS idx_tx_lines_currency ON transaction_lines(currency_code);
CREATE INDEX IF NOT EXISTS idx_tx_lines_tx_id ON transaction_lines(transaction_id);
CREATE INDEX IF NOT EXISTS idx_tx_date ON transactions(tx_date);
CREATE INDEX IF NOT EXISTS idx_fx_contracts_acc ON fx_contracts(account_id);
CREATE INDEX IF NOT EXISTS idx_fx_contract_payments ON fx_contract_payments(contract_id);
CREATE INDEX IF NOT EXISTS idx_sessions_token ON app_sessions(token);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON app_sessions(user_id);

